// xxtea128.h
#ifndef XXTEA128_H
#define XXTEA128_H

#include <stddef.h>
#include <stdint.h>

// Encrypt/decrypt a single 16-byte block using XXTEA-style mixing on 4x32-bit words.
void xxtea128_encrypt_block(uint8_t out[16], const uint8_t in[16], const uint8_t key[16]);
void xxtea128_decrypt_block(uint8_t out[16], const uint8_t in[16], const uint8_t key[16]);

// Returns 1 on success, 0 before modifying data on invalid pointers/length.
// Max length: 2^36 bytes per call. Never reuse key+nonce; calls restart counter at 0.
// CTR mode (same function for encrypt/decrypt): XOR data with keystream blocks
// generated by encrypting (nonce[12] || counter_le32).
int xxtea128_ctr_xor(uint8_t *data, size_t len, const uint8_t key[16], const uint8_t nonce12[12]);

#endif
